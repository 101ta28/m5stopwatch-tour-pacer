#!/usr/bin/env python3
"""Bake grayscale VLW glyphs for the UI; the checked-in result builds without Python."""
from pathlib import Path
import re
import struct

from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
src = root / "StopWatchTourGuide"
font_dir = Path("/usr/share/fonts/opentype/noto")
# Include all UI strings and the configured course. The display driver falls
# back to its Japanese font for names from older records or edited courses.
chars = set(chr(i) for i in range(32, 127))
for path in (src / "src/App.cpp", src / "CourseConfig.h"):
    for literal in re.findall(r'"([^"\n]*)"', path.read_text()):
        chars.update(literal)


def vlw(size, weight, alphabet):
    font = ImageFont.truetype(str(font_dir / f"NotoSansCJK-{weight}.ttc"), size, index=0)
    assert font.getname()[0].startswith("Noto Sans CJK JP")
    metrics = bytearray()
    pixels = bytearray()
    for c in sorted(alphabet):
        left, top, right, bottom = font.getbbox(c, anchor="ls")
        width, height = right - left, bottom - top
        metrics.extend(struct.pack(">7i", ord(c), height, width, round(font.getlength(c)), -top, left, 0))
        if width and height:
            glyph = Image.new("L", (width, height))
            ImageDraw.Draw(glyph).text((-left, -top), c, font=font, anchor="ls", fill=255)
            pixels.extend(glyph.tobytes())
    return struct.pack(">6I", len(alphabet), 11, size, 0, round(size * .86), round(size * .14)) + metrics + pixels


if __name__ == "__main__":
    out = src / "src/fonts"
    out.mkdir(exist_ok=True)
    with (out / "GlyphData.h").open("w") as f:
        print("// Generated by scripts/make-ui-fonts.py. See OFL.txt.", file=f)
        for size, weight in [(20, "Regular"), (24, "Medium"), (32, "Bold"), (56, "Medium"), (76, "Medium")]:
            data = vlw(size, weight, chars if size <= 32 else "0123456789:-")
            print(f"static constexpr uint8_t pixels{size}[] = {{", file=f)
            for i in range(0, len(data), 32):
                print(",".join(map(str, data[i:i+32])) + ",", file=f)
            print("};", file=f)
